export function translate(
  locale: Locale,
  portugueseText: string,
  englishFallback: string,
): string {
  return locale === "pt-BR"
    ? portugueseText
    : (englishByPortuguese[portugueseText] ?? englishFallback);
}

export function translateError(locale: Locale, message: string): string {
  return locale === "en" ? (englishErrors[message] ?? message) : message;
}
